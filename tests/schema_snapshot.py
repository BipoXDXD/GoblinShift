"""Retrato do DDL de um schema lido do catálogo do PostgreSQL.

O `compare_metadata` do Alembic ignora `CheckConstraint` e o predicado de índice parcial, então um
CHECK ou um `WHERE` diferente entre a migração e o `tables.py` passa por ele. Aqui o próprio
PostgreSQL escreve cada definição (`format_type`, `pg_get_constraintdef`, `pg_get_indexdef`): dois
schemas com o mesmo DDL geram retratos iguais, qualquer que seja o caminho que os criou.

As funções do catálogo qualificam um nome com o schema só quando ele não está visível no
`search_path`. Por isso o retrato fixa o `search_path` no schema lido (só nesta transação): as
definições saem sem prefixo e dá para comparar `public` com outro schema. A exceção é o
`pg_get_indexdef`, que sempre qualifica a tabela (`ON public.tabela`); esse prefixo sai na consulta.
"""

from dataclasses import dataclass

from sqlalchemy import Connection, text

# Tabela do próprio Alembic, que não está no `metadata`.
_IGNORED_TABLES = ("alembic_version",)

_COLUMNS = text(
    """
    SELECT t.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
           coalesce(
               pg_get_expr(d.adbin, d.adrelid),
               CASE a.attidentity
                   WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY'
                   WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
               END
           )
    FROM pg_attribute a
    JOIN pg_class t ON t.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE n.nspname = :schema
      AND t.relkind IN ('r', 'p')
      AND t.relname <> ALL(:ignored)
      AND a.attnum > 0
      AND NOT a.attisdropped
    """
)

_CONSTRAINTS = text(
    """
    SELECT t.relname, c.conname, pg_get_constraintdef(c.oid), c.convalidated
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = :schema
      AND t.relkind IN ('r', 'p')
      AND t.relname <> ALL(:ignored)
    """
)

_INDEXES = text(
    """
    SELECT t.relname, i.relname,
           replace(pg_get_indexdef(i.oid), ' ON ' || quote_ident(n.nspname) || '.', ' ON '),
           x.indisvalid
    FROM pg_index x
    JOIN pg_class i ON i.oid = x.indexrelid
    JOIN pg_class t ON t.oid = x.indrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = :schema
      AND t.relkind IN ('r', 'p')
      AND t.relname <> ALL(:ignored)
    """
)


@dataclass(frozen=True)
class SchemaSnapshot:
    """DDL de um schema, cada parte indexada por (tabela, nome).

    `columns`: tipo (`format_type`), NOT NULL (`attnotnull`) e default (`pg_get_expr`; numa coluna
    identity, `GENERATED ALWAYS|BY DEFAULT AS IDENTITY`). `constraints`: `pg_get_constraintdef`,
    que inclui CHECK, FK com `ON DELETE`, UNIQUE, PK e, no PostgreSQL 18, os NOT NULL nomeados, mais
    `convalidated` (falso numa constraint deixada `NOT VALID`). `indexes`: `pg_get_indexdef`, com
    colunas, método, UNIQUE e o predicado do índice parcial, mais `indisvalid` (falso num índice
    `CONCURRENTLY` que falhou no meio e ficou inválido, que o `pg_get_indexdef` não mostra).
    """

    columns: dict[tuple[str, str], tuple[str, bool, str | None]]
    constraints: dict[tuple[str, str], tuple[str, bool]]
    indexes: dict[tuple[str, str], tuple[str, bool]]


def schema_snapshot(conn: Connection, schema: str) -> SchemaSnapshot:
    """Lê o DDL das tabelas de `schema`, sem a `alembic_version`.

    Fixa o `search_path` em `schema` até o fim da transação corrente (`SET LOCAL`).
    """
    conn.execute(
        text("SELECT set_config('search_path', quote_ident(:schema), true)"), {"schema": schema}
    )
    params = {"schema": schema, "ignored": list(_IGNORED_TABLES)}
    columns = {
        (table, column): (type_, not_null, default)
        for table, column, type_, not_null, default in conn.execute(_COLUMNS, params)
    }
    constraints = {
        (table, name): (definition, validated)
        for table, name, definition, validated in conn.execute(_CONSTRAINTS, params)
    }
    indexes = {
        (table, name): (definition, valid)
        for table, name, definition, valid in conn.execute(_INDEXES, params)
    }
    return SchemaSnapshot(columns=columns, constraints=constraints, indexes=indexes)
